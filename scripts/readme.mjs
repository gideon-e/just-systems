#!/usr/bin/env node
// Rebuilds the README's skill table from each skills/<name>/SKILL.md frontmatter,
// so the README cannot drift from the skills.
//   node scripts/readme.mjs          rewrite README.md
//   node scripts/readme.mjs --check  exit 1 if README.md is stale (CI runs this)
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const START = "<!-- skills:start (generated by scripts/readme.mjs; edit SKILL.md, not this) -->";
const END = "<!-- skills:end -->";

// Reads the frontmatter keys this script needs: plain, quoted, and folded (> or >-) scalars.
export function frontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  if (!m) return {};
  const out = {};
  let key = null;
  for (const line of m[1].split("\n")) {
    const kv = line.match(/^([\w-]+):\s*(.*)$/);
    if (kv) {
      key = kv[1];
      const v = kv[2].trim();
      out[key] = /^>-?$/.test(v) ? "" : v.replace(/^(["'])(.*)\1$/, "$2");
    } else if (key && /^\s+\S/.test(line)) {
      out[key] = (out[key] + " " + line.trim()).trim();
    }
  }
  return out;
}

export function skills(dir = join(root, "skills")) {
  return readdirSync(dir)
    .filter((d) => existsSync(join(dir, d, "SKILL.md")))
    .sort()
    .map((d) => {
      const fm = frontmatter(readFileSync(join(dir, d, "SKILL.md"), "utf8"));
      if (!fm.name || !fm.description) throw new Error(`skills/${d}/SKILL.md: frontmatter needs name and description`);
      return fm;
    });
}

export function block(list) {
  const cell = (s) => s.replace(/\|/g, "\\|");
  const rows = list.map((s) => `| \`/just-systems:${s.name}\` | ${cell(s.description)} |`);
  const codex = list.map((s) => `\`$just-systems:${s.name}\``).join(", ");
  return [START, "| Skill | What it does |", "|---|---|", ...rows, "", `In Codex, invoke ${codex}.`, END].join("\n");
}

export function render(readme, list) {
  const i = readme.indexOf(START), j = readme.indexOf(END);
  if (i < 0 || j < i) throw new Error("README.md: skills markers missing");
  return readme.slice(0, i) + block(list) + readme.slice(j + END.length);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const path = join(root, "README.md");
  const now = readFileSync(path, "utf8");
  const next = render(now, skills());
  if (process.argv.includes("--check")) {
    if (now !== next) {
      console.error("README.md is out of date. Run: node scripts/readme.mjs");
      process.exit(1);
    }
    console.log("README.md matches the skills.");
  } else {
    writeFileSync(path, next);
    console.log("README.md updated.");
  }
}
